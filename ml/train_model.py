"""Reproducible train/evaluate workflow.

REAL mode (default): needs a labelled CSV of real pilot batches (see data/pilot/labelled_batches_TEMPLATE.csv).
   Refuses to train below MIN_ROWS / MIN_MINORITY because tiny samples give meaningless metrics.
   python -m ml.train_model --csv data/pilot/labelled_batches.csv
SYNTHETIC DEMO mode: labels are produced by the app's own rules, so any metric only shows the pipeline runs.
   python -m ml.train_model --synthetic-demo
"""
import argparse, json, random, sys
from datetime import date, timedelta
from pathlib import Path
import joblib, pandas as pd, sklearn
from sklearn.dummy import DummyClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, f1_score, precision_score, recall_score
from sklearn.model_selection import GroupShuffleSplit, StratifiedKFold, cross_val_score, train_test_split
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import config
from ml.preprocessing import FEATURES, TARGET, build_pipeline

MIN_ROWS, MIN_MINORITY = 200, 30


def make_synthetic_demo(path, n=600, seed=7):
    """SYNTHETIC rows; label = 1 when the rule engine says 'Elevated'. Pipeline demo only - not evidence."""
    from modules.risk_assessment import assess
    rnd = random.Random(seed); rows = []
    for _ in range(n):
        b = dict(product=rnd.choice(["Tamarind", "Honey", "Other NTFP"]),
                 collection_date=(date.today() - timedelta(days=rnd.randint(1, 120))).isoformat(),
                 storage_humidity_pct=round(rnd.uniform(40, 95), 1), storage_temp_c=round(rnd.uniform(18, 42), 1),
                 moisture_pct=round(rnd.uniform(8, 24), 1), storage_type=rnd.choice(config.STORAGE_TYPES),
                 packaging_type=rnd.choice(config.PACKAGING_TYPES), visible_mold=int(rnd.random() < .05),
                 pest_signs=int(rnd.random() < .08))
        r = assess(b)
        rows.append({**{k: b.get(k) for k in FEATURES if k != "age_days"},
                     "age_days": (date.today() - date.fromisoformat(b["collection_date"])).days,
                     TARGET: int(r["level"] == "Elevated")})
    df = pd.DataFrame(rows)[FEATURES + [TARGET]]
    Path(path).parent.mkdir(parents=True, exist_ok=True); df.to_csv(path, index=False)
    return df


def _scores(y, p):
    return {"precision": float(precision_score(y, p, zero_division=0)), "recall": float(recall_score(y, p, zero_division=0)),
            "f1": float(f1_score(y, p, zero_division=0)), "confusion_matrix[[TN,FP],[FN,TP]]": confusion_matrix(y, p, labels=[0, 1]).tolist()}


def train(df, out_dir, synthetic=False, exclude=(), seed=42, group_col="producer_group"):
    df = df.dropna(subset=[TARGET]).copy()
    if not set(df[TARGET].unique()) <= {0, 1}:
        raise ValueError(f"'{TARGET}' must be 0/1.")
    missing = [c for c in FEATURES if c not in df.columns]
    if missing:
        raise ValueError(f"Missing columns: {missing}")
    vc = df[TARGET].value_counts()
    if not synthetic and (len(df) < MIN_ROWS or vc.min() < MIN_MINORITY or len(vc) < 2):
        raise ValueError(f"Refusing to train: need >= {MIN_ROWS} rows and >= {MIN_MINORITY} per class; got "
                         f"{len(df)} rows, class counts {vc.to_dict()}. Collect more real pilot data.")
    X, y = df[FEATURES], df[TARGET].astype(int)
    if group_col in df and df[group_col].nunique() >= 5:   # keep whole producer groups out of training
        tr, te = next(GroupShuffleSplit(test_size=.25, random_state=seed).split(X, y, df[group_col]))
        split = "GroupShuffleSplit by producer_group"
    else:
        tr, te = train_test_split(range(len(df)), test_size=.25, stratify=y, random_state=seed)
        split = "stratified 75/25 split"
    Xtr, Xte, ytr, yte = X.iloc[tr], X.iloc[te], y.iloc[tr], y.iloc[te]
    base = DummyClassifier(strategy="most_frequent").fit(Xtr, ytr)
    cands = {"logistic_regression": LogisticRegression(max_iter=1000, class_weight="balanced"),
             "random_forest": RandomForestClassifier(n_estimators=150, max_depth=6, class_weight="balanced", random_state=seed)}
    cv = StratifiedKFold(5, shuffle=True, random_state=seed)
    cvf1 = {}
    for name, est in cands.items():   # model choice uses TRAIN data only (no test leakage)
        pipe, _ = build_pipeline(est, exclude)
        cvf1[name] = float(cross_val_score(pipe, Xtr, ytr, cv=cv, scoring="f1").mean())
    best = max(cvf1, key=cvf1.get)
    pipe, used = build_pipeline(cands[best], exclude); pipe.fit(Xtr, ytr)
    metrics = {"SYNTHETIC_DEMO": bool(synthetic),
               "warning": ("SYNTHETIC labels generated by the app's own rules: metrics only show the pipeline runs; "
                           "they say NOTHING about real-world accuracy.") if synthetic else
                          "Metrics are from a held-out test set of the supplied pilot data only; revalidate before relying on them.",
               "n_rows": len(df), "n_train": len(tr), "n_test": len(te), "class_counts": {int(k): int(v) for k, v in vc.items()},
               "split": split, "selected_model": best, "cv_f1_on_train": cvf1, "features_used": used,
               "baseline_most_frequent": _scores(yte, base.predict(Xte)), "model_test": _scores(yte, pipe.predict(Xte)),
               "sklearn_version": sklearn.__version__, "trained_on": date.today().isoformat()}
    out = Path(out_dir); out.mkdir(parents=True, exist_ok=True)
    joblib.dump(pipe, out / "model.joblib"); (out / "metrics.json").write_text(json.dumps(metrics, indent=2))
    return metrics


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv"); ap.add_argument("--synthetic-demo", action="store_true")
    ap.add_argument("--exclude", nargs="*", default=[], help="feature columns to drop (e.g. visible_mold pest_signs)")
    a = ap.parse_args(); root = Path(config.ROOT)
    if a.synthetic_demo:
        d = make_synthetic_demo(root / "data/sample_data/synthetic_rule_labelled_demo.csv")
        m = train(d, root / "models/demo", synthetic=True, exclude=a.exclude)
    elif a.csv:
        m = train(pd.read_csv(a.csv), root / "models/real", exclude=a.exclude)
    else:
        ap.error("give --csv <labelled pilot csv> or --synthetic-demo")
    print(json.dumps(m, indent=2))
